#include <iostream>
using namespace std;

int main()
{
    int a, b;

    a = 8 + 2 * 3 / 6;
    b = (8 + 2) * 3 / 6;

    cout << "A = 8 + 2 * 3 / 6" << endl;
    cout << "B = (8 + 2) * 3 / 6" << endl;
    cout << endl;

    cout << "Hasil dari A = " << a << endl;
    cout << "Hasil dari B = " << b << endl;

    return 0;
}
